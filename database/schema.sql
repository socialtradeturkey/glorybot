-- GLORYBOT application schema for Neon PostgreSQL.
-- Apply deliberately through Neon SQL Editor; the app does not run DDL at startup.

CREATE TABLE IF NOT EXISTS trading_signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signal_id TEXT NOT NULL UNIQUE,
  symbol TEXT NOT NULL DEFAULT 'XAUUSD' CHECK (symbol = 'XAUUSD'),
  timeframe TEXT NOT NULL DEFAULT 'M5' CHECK (timeframe = 'M5'),
  direction TEXT NOT NULL CHECK (direction IN ('BUY', 'SELL')),
  signal_time TIMESTAMPTZ NOT NULL,
  entry_price NUMERIC(18, 6) NOT NULL CHECK (entry_price > 0),
  raw_payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT trading_signals_one_per_bar UNIQUE (symbol, timeframe, signal_time)
);

CREATE INDEX IF NOT EXISTS trading_signals_recent_idx
  ON trading_signals (signal_time DESC, id DESC);
CREATE INDEX IF NOT EXISTS trading_signals_direction_idx
  ON trading_signals (direction, signal_time DESC);

CREATE TABLE IF NOT EXISTS market_bars (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol TEXT NOT NULL DEFAULT 'XAUUSD' CHECK (symbol = 'XAUUSD'),
  timeframe TEXT NOT NULL DEFAULT 'M5' CHECK (timeframe = 'M5'),
  open_time TIMESTAMPTZ NOT NULL,
  close_time TIMESTAMPTZ NOT NULL,
  open_price NUMERIC(18, 6) NOT NULL CHECK (open_price > 0),
  high_price NUMERIC(18, 6) NOT NULL CHECK (high_price > 0),
  low_price NUMERIC(18, 6) NOT NULL CHECK (low_price > 0),
  close_price NUMERIC(18, 6) NOT NULL CHECK (close_price > 0),
  is_closed BOOLEAN NOT NULL CHECK (is_closed),
  received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT market_bars_five_minute_window CHECK (close_time = open_time + INTERVAL '5 minutes'),
  CONSTRAINT market_bars_valid_range CHECK (
    low_price <= LEAST(open_price, close_price)
    AND high_price >= GREATEST(open_price, close_price, low_price)
  ),
  CONSTRAINT market_bars_one_per_bar UNIQUE (symbol, timeframe, open_time)
);

CREATE INDEX IF NOT EXISTS market_bars_closed_window_idx
  ON market_bars (symbol, timeframe, open_time, close_time)
  WHERE is_closed = TRUE;

CREATE TABLE IF NOT EXISTS signal_performance (
  signal_ref BIGINT PRIMARY KEY REFERENCES trading_signals (id) ON DELETE CASCADE,
  mfe NUMERIC(18, 6) NOT NULL DEFAULT 0 CHECK (mfe >= 0),
  mae NUMERIC(18, 6) NOT NULL DEFAULT 0 CHECK (mae >= 0),
  current_move NUMERIC(18, 6) NOT NULL DEFAULT 0,
  bars_count INTEGER NOT NULL DEFAULT 0 CHECK (bars_count >= 0),
  last_bar_time TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS telegram_logs (
  signal_ref BIGINT PRIMARY KEY REFERENCES trading_signals (id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 1),
  telegram_message_id TEXT,
  response_status SMALLINT,
  error_code TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS telegram_logs_status_idx
  ON telegram_logs (status, updated_at DESC);

CREATE TABLE IF NOT EXISTS api_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id TEXT NOT NULL,
  event_type TEXT NOT NULL CHECK (event_type IN ('signal', 'bar', 'invalid', 'health')),
  status_code SMALLINT NOT NULL CHECK (status_code BETWEEN 100 AND 599),
  result_code TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS api_logs_recent_idx ON api_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS api_logs_request_idx ON api_logs (request_id);
